"""Build the final results table straight from MLflow (only runs that scored the test set).

Usage (from the repo root):  python scripts/make_results_table.py
Writes docs/results.md. Every number comes from a logged run; nothing is typed by hand.
"""
import argparse
import os
from pathlib import Path

import mlflow
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
EXPERIMENT = "cmapss-rul"
MODEL_NAMES = {"xgboost": "XGBoost", "lstm": "LSTM", "gru": "GRU",
               "cnn": "1D-CNN", "transformer": "Transformer"}


def load_final_runs() -> pd.DataFrame:
    mlflow.set_tracking_uri(os.environ.get("MLFLOW_TRACKING_URI", f"sqlite:///{ROOT / 'mlflow.db'}"))
    runs = mlflow.search_runs(experiment_names=[EXPERIMENT],
                              filter_string="metrics.test_rmse > 0")   # only runs that scored the test set
    df = runs.rename(columns={"params.subset": "subset", "params.model": "model",
                              "params.window": "window", "params.seed": "seed",
                              "metrics.test_rmse": "test_rmse",
                              "metrics.test_nasa_score": "test_nasa"})
    df["window"] = df["window"].astype(int)
    return df[["subset", "model", "window", "seed", "test_rmse", "test_nasa"]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "results.md"))
    args = ap.parse_args()

    df = load_final_runs()
    warnings = []

    # protocol check: the test set is touched once per (subset, model, window, seed)
    dup = df[df.duplicated(["subset", "model", "window", "seed"], keep=False)]
    for key, g in dup.groupby(["subset", "model", "window", "seed"]):
        warnings.append(f"test set scored {len(g)} times for {key}; keeping the first logged run")
    df = df.sort_values("seed").drop_duplicates(["subset", "model", "window", "seed"])

    g = df.groupby(["subset", "model", "window"]).agg(
        seeds=("seed", "nunique"),
        rmse_mean=("test_rmse", "mean"), rmse_sd=("test_rmse", "std"),
        nasa_mean=("test_nasa", "mean"), nasa_sd=("test_nasa", "std")).reset_index()
    for _, r in g[g["seeds"] < 3].iterrows():
        warnings.append(f"only {r.seeds} seed(s) for {r.subset} {r.model} window {r.window}")

    lines = ["# Results (official test set, last window per engine)", "",
             "Generated by `scripts/make_results_table.py` from MLflow. Mean +- sample standard "
             "deviation over seeds; lower is better. The test set is scored once per "
             "(subset, model, window, seed).", ""]
    for subset, sub in g.groupby("subset"):
        lines += [f"## {subset}", "", "| Model | Window | Seeds | Test RMSE | Test NASA score |",
                  "|---|---|---|---|---|"]
        for _, r in sub.sort_values("rmse_mean").iterrows():
            rmse_sd = "n/a" if pd.isna(r.rmse_sd) else f"{r.rmse_sd:.2f}"     # one seed has no spread
            nasa_sd = "n/a" if pd.isna(r.nasa_sd) else f"{r.nasa_sd:,.0f}"
            lines.append(f"| {MODEL_NAMES.get(r.model, r.model)} | {r.window} | {r.seeds} | "
                         f"{r.rmse_mean:.2f} +- {rmse_sd} | {r.nasa_mean:,.0f} +- {nasa_sd} |")
        lines.append("")
    if warnings:
        lines += ["## Warnings", ""] + [f"- {w}" for w in warnings] + [""]

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
